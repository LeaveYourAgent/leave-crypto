/**
 * The cryptographic primitives from API contract section 1, as pure functions over bytes, so
 * they can be checked against the shared test vectors (vectors/v1.json, generated by Leave's
 * server code). The Android counterpart of ios/Sources/LeaveCryptoCore/LeaveCryptoCore.swift,
 * function for function. Nothing here touches the Keystore, a file or the network; the app's
 * bridge (android/app-bridge/) does that.
 *
 * Wire formats: AES-256-GCM is `nonce(12) ‖ ciphertext ‖ tag(16)`; HPKE is
 * `enc(65) ‖ ciphertext ‖ tag`; every string in the protocol is UTF-8 and every binary value
 * crossing an API is base64url without padding.
 *
 * Where each primitive comes from. Android's own providers: AES-GCM, HMAC, SHA-256, ECDSA and
 * RSA-OAEP. Bouncy Castle, called directly and never installed as a provider: HPKE (RFC 9180),
 * Argon2id (RFC 9106) and the one curve multiplication that turns the account scalar into its
 * public key. Android has none of those three.
 */
object LeaveCryptoCore {
  class Failure(message: String) : Exception(message)

  private const val BAD_KEY_LENGTH = "Key is not 32 bytes."
  private const val BAD_WIRE = "Ciphertext is malformed."
  private const val BAD_PUBLIC_KEY = "Public key is malformed."

  private val random = SecureRandom()

  fun randomBytes(count: Int): ByteArray = ByteArray(count).also { random.nextBytes(it) }

  private fun utf8(s: String): ByteArray = s.toByteArray(Charsets.UTF_8)

  // Record encryption (recordAead)

  fun aad(recordType: String, recordId: String): ByteArray = utf8("leave:v1:$recordType:$recordId")

  /** AES-256-GCM seal. A null nonce draws a random one (production); the vectors pass theirs. */
  fun seal(key: ByteArray, plaintext: ByteArray, aad: ByteArray, nonce: ByteArray? = null): ByteArray {
    if (key.size != 32) throw Failure(BAD_KEY_LENGTH)
    val n = nonce ?: randomBytes(12)
    if (n.size != 12) throw Failure(BAD_WIRE)
    val cipher = Cipher.getInstance("AES/GCM/NoPadding")
    cipher.init(Cipher.ENCRYPT_MODE, SecretKeySpec(key, "AES"), GCMParameterSpec(128, n))
    cipher.updateAAD(aad)
    return n + cipher.doFinal(plaintext)
  }

  /** Throws when the key, the associated data or a single byte of the wire is not what was sealed. */
  fun open(key: ByteArray, wire: ByteArray, aad: ByteArray): ByteArray {
    if (key.size != 32) throw Failure(BAD_KEY_LENGTH)
    if (wire.size < 12 + 16) throw Failure(BAD_WIRE)
    val cipher = Cipher.getInstance("AES/GCM/NoPadding")
    cipher.init(Cipher.DECRYPT_MODE, SecretKeySpec(key, "AES"), GCMParameterSpec(128, wire, 0, 12))
    cipher.updateAAD(aad)
    return cipher.doFinal(wire, 12, wire.size - 12)
  }

  // HKDF-SHA256 (RFC 5869): extract, then expand.

  private fun hmac(key: ByteArray, vararg parts: ByteArray): ByteArray =
      Mac.getInstance("HmacSHA256").run {
        init(SecretKeySpec(key, "HmacSHA256"))
        parts.forEach { update(it) }
        doFinal()
      }

  fun hkdfExtract(salt: ByteArray, inputKeyMaterial: ByteArray): ByteArray = hmac(if (salt.isEmpty()) ByteArray(32) else salt, inputKeyMaterial)

  fun hkdf(inputKeyMaterial: ByteArray, salt: ByteArray, info: ByteArray, outputByteCount: Int): ByteArray =
      hkdfExpand(hkdfExtract(salt, inputKeyMaterial), info, outputByteCount)

  fun hkdfExpand(pseudoRandomKey: ByteArray, info: ByteArray, outputByteCount: Int): ByteArray {
    var block = ByteArray(0)
    var output = ByteArray(0)
    var counter = 1
    while (output.size < outputByteCount) {
      block = hmac(pseudoRandomKey, block, info, byteArrayOf(counter.toByte()))
      output += block
      counter += 1
    }
    return output.copyOf(outputByteCount)
  }

  // Share wrap of a DEK (shareWrap)

  fun wrapKey(share: ByteArray, recordId: String): ByteArray = hkdf(share, utf8(recordId), utf8("leave:v1:dek-wrap"), 32)

  fun shareWrap(share: ByteArray, recordType: String, recordId: String, dek: ByteArray, nonce: ByteArray? = null): ByteArray =
      seal(wrapKey(share, recordId), dek, aad(recordType, recordId), nonce)

  fun shareUnwrap(share: ByteArray, recordType: String, recordId: String, wire: ByteArray): ByteArray =
      open(wrapKey(share, recordId), wire, aad(recordType, recordId))

  // Account key (accountKey): rejection-sampled P-256 scalar

  private val curve = CustomNamedCurves.getByName("secp256r1")

  /** 1 ≤ scalar ≤ n − 1, as a big-endian number; no modular reduction. */
  fun scalarInRange(scalar: ByteArray): Boolean {
    if (scalar.size != 32) return false
    val value = BigInteger(1, scalar)
    return value.signum() > 0 && value < curve.n
  }

  fun accountScalar(share: ByteArray, accountId: String): ByteArray {
    var counter = 0
    while (true) {
      val candidate = hkdf(share, utf8("leave:v1:account-key"), utf8("$accountId:$counter"), 32)
      if (scalarInRange(candidate)) return candidate
      counter += 1
    }
  }

  /** The public half of a scalar: the uncompressed point, `0x04 ‖ x(32) ‖ y(32)`. */
  fun publicKeyRaw(scalar: ByteArray): ByteArray {
    if (!scalarInRange(scalar)) throw Failure("Derived scalar is out of range.")
    return FixedPointCombMultiplier().multiply(curve.g, BigInteger(1, scalar)).normalize().getEncoded(false)
  }

  /** What every P-256 public key's SPKI DER starts with; the 65-byte point follows. */
  private val spkiHeader = hex("3059301306072a8648ce3d020106082a8648ce3d030107034200")

  fun spkiOfRaw(raw: ByteArray): ByteArray {
    if (raw.size != 65 || raw[0] != 4.toByte()) throw Failure(BAD_PUBLIC_KEY)
    return spkiHeader + raw
  }

  /** The point inside a P-256 SPKI, checked to be on the curve. Anything else is refused. */
  fun rawOfSpki(spki: ByteArray): ByteArray {
    if (spki.size != spkiHeader.size + 65 || !spki.copyOf(spkiHeader.size).contentEquals(spkiHeader)) throw Failure(BAD_PUBLIC_KEY)
    val raw = spki.copyOfRange(spkiHeader.size, spki.size)
    try {
      if (raw[0] != 4.toByte() || !curve.curve.decodePoint(raw).isValid) throw Failure(BAD_PUBLIC_KEY)
    } catch (e: IllegalArgumentException) {
      throw Failure(BAD_PUBLIC_KEY)
    }
    return raw
  }

  /** The account key's public half, as the server holds it (SPKI DER). */
  fun accountPublicKeySpki(share: ByteArray, accountId: String): ByteArray = spkiOfRaw(publicKeyRaw(accountScalar(share, accountId)))

  // HPKE: DHKEM(P-256, HKDF-SHA256), HKDF-SHA256, AES-256-GCM, base mode

  private fun hpke() = HPKE(HPKE.mode_base, HPKE.kem_P256_SHA256, HPKE.kdf_HKDF_SHA256, HPKE.aead_AES_GCM256)

  /** A null `ephemeralIkm` draws a new sender key (production); the vectors pass theirs. */
  fun hpkeSeal(recipientSpki: ByteArray, info: String, plaintext: ByteArray, ephemeralIkm: ByteArray? = null): ByteArray {
    val suite = hpke()
    val recipient = suite.deserializePublicKey(rawOfSpki(recipientSpki))
    val sender =
        if (ephemeralIkm == null) suite.setupBaseS(recipient, utf8(info))
        else suite.setupBaseS(recipient, utf8(info), suite.deriveKeyPair(ephemeralIkm))
    return sender.encapsulation + sender.seal(ByteArray(0), plaintext)
  }

  fun hpkeOpen(recipientScalar: ByteArray, info: String, wire: ByteArray): ByteArray {
    if (wire.size <= 65 + 16) throw Failure(BAD_WIRE)
    val suite = hpke()
    val recipient = suite.deserializePrivateKey(recipientScalar, publicKeyRaw(recipientScalar))
    return suite.setupBaseR(wire.copyOf(65), recipient, utf8(info)).open(ByteArray(0), wire.copyOfRange(65, wire.size))
  }

  /**
   * HPKE open for a recipient whose private key cannot be handed over: this phone's own
   * agreement key, which lives in the Android Keystore and only ever answers one question,
   * "what do you and this public key agree on?". `agree` asks it; everything else of RFC 9180's
   * base mode (the labelled key derivation and the AES-256-GCM open) is done here.
   *
   * Checked against the same vectors as `hpkeOpen`, with an ordinary key answering `agree`.
   */
  fun hpkeOpenWith(agree: (senderPublicRaw: ByteArray) -> ByteArray, recipientPublicRaw: ByteArray, info: String, wire: ByteArray): ByteArray {
    if (wire.size <= 65 + 16) throw Failure(BAD_WIRE)
    val enc = wire.copyOf(65)
    rawOfSpki(spkiOfRaw(enc)) // the sender's point is on the curve, or nothing is asked of the key
    fun i2osp(n: Int, length: Int) = ByteArray(length) { (n shr (8 * (length - 1 - it))).toByte() }
    val kemSuite = utf8("KEM") + i2osp(0x0010, 2)
    val hpkeSuite = utf8("HPKE") + i2osp(0x0010, 2) + i2osp(0x0001, 2) + i2osp(0x0002, 2)
    fun labeledExtract(suite: ByteArray, salt: ByteArray, label: String, ikm: ByteArray) = hkdfExtract(salt, utf8("HPKE-v1") + suite + utf8(label) + ikm)
    fun labeledExpand(suite: ByteArray, prk: ByteArray, label: String, context: ByteArray, length: Int) =
        hkdfExpand(prk, i2osp(length, 2) + utf8("HPKE-v1") + suite + utf8(label) + context, length)

    val dh = agree(enc)
    if (dh.size != 32) throw Failure(BAD_WIRE)
    val sharedSecret = labeledExpand(kemSuite, labeledExtract(kemSuite, ByteArray(0), "eae_prk", dh), "shared_secret", enc + recipientPublicRaw, 32)
    val context = byteArrayOf(0) + labeledExtract(hpkeSuite, ByteArray(0), "psk_id_hash", ByteArray(0)) + labeledExtract(hpkeSuite, ByteArray(0), "info_hash", utf8(info))
    val secret = labeledExtract(hpkeSuite, sharedSecret, "secret", ByteArray(0))
    val key = labeledExpand(hpkeSuite, secret, "key", context, 32)
    val nonce = labeledExpand(hpkeSuite, secret, "base_nonce", context, 12)
    return open(key, nonce + wire.copyOfRange(65, wire.size), ByteArray(0))
  }

  /** What two P-256 keys agree on (the x coordinate), for an ordinary private key. The tests' stand-in for the Keystore. */
  fun agreement(scalar: ByteArray, publicRaw: ByteArray): ByteArray =
      javax.crypto.KeyAgreement.getInstance("ECDH").run {
        init(KeyFactory.getInstance("EC").generatePrivate(ECPrivateKeySpec(BigInteger(1, scalar), p256)))
        doPhase(KeyFactory.getInstance("EC").generatePublic(X509EncodedKeySpec(spkiOfRaw(publicRaw))), true)
        generateSecret()
      }

  // Session grant (grant)

  /**
   * SHA-256 for the hash and for MGF1, empty label. Said in full on purpose: asked for by name
   * alone, Android pairs a SHA-256 hash with a SHA-1 MGF1, and the server could not open it.
   */
  private val oaep = OAEPParameterSpec("SHA-256", "MGF1", MGF1ParameterSpec.SHA256, PSource.PSpecified.DEFAULT)

  /**
   * RSA-OAEP of the 32-byte session key to the server's KMS public key (SPKI DER). Output is
   * 384 bytes for RSA-3072.
   */
  fun rsaSeal(serverSpki: ByteArray, sessionKey: ByteArray): ByteArray {
    if (sessionKey.size != 32) throw Failure(BAD_KEY_LENGTH)
    val key = try {
      KeyFactory.getInstance("RSA").generatePublic(X509EncodedKeySpec(serverSpki))
    } catch (e: Exception) {
      throw Failure("Server key is malformed: ${e.message ?: ""}")
    }
    return Cipher.getInstance("RSA/ECB/OAEPPadding").run {
      init(Cipher.ENCRYPT_MODE, key, oaep)
      doFinal(sessionKey)
    }
  }

  /** Test helper: the inverse with a PKCS#8 private key (only the vectors carry one). */
  fun rsaOpen(privateKeyPkcs8: ByteArray, sealed: ByteArray): ByteArray =
      Cipher.getInstance("RSA/ECB/OAEPPadding").run {
        init(Cipher.DECRYPT_MODE, KeyFactory.getInstance("RSA").generatePrivate(PKCS8EncodedKeySpec(privateKeyPkcs8)), oaep)
        doFinal(sealed)
      }

  fun grantAad(sessionId: String, recordId: String): ByteArray = utf8("leave:v1:grant:$sessionId:$recordId")

  fun sealDek(sessionKey: ByteArray, sessionId: String, recordId: String, dek: ByteArray, nonce: ByteArray? = null): ByteArray =
      seal(sessionKey, dek, grantAad(sessionId, recordId), nonce)

  // Signatures (signatures)

  private val p256: ECParameterSpec =
      AlgorithmParameters.getInstance("EC").run {
        init(ECGenParameterSpec("secp256r1"))
        getParameterSpec(ECParameterSpec::class.java)
      }

  /** ECDSA P-256 over SHA-256. Takes the signature raw (`r ‖ s`, 64 bytes) or as DER. */
  fun verify(spki: ByteArray, message: ByteArray, signature: ByteArray): Boolean {
    rawOfSpki(spki)
    val der = if (signature.size == 64) derOfRaw(signature) else signature
    return try {
      Signature.getInstance("SHA256withECDSA").run {
        initVerify(KeyFactory.getInstance("EC").generatePublic(X509EncodedKeySpec(spki)))
        update(message)
        verify(der)
      }
    } catch (e: java.security.SignatureException) {
      false
    }
  }

  /** The account key's signature over `message`, raw `r ‖ s` (what the server takes). */
  fun sign(scalar: ByteArray, message: ByteArray): ByteArray {
    if (!scalarInRange(scalar)) throw Failure("Derived scalar is out of range.")
    val der =
        Signature.getInstance("SHA256withECDSA").run {
          initSign(KeyFactory.getInstance("EC").generatePrivate(ECPrivateKeySpec(BigInteger(1, scalar), p256)))
          update(message)
          sign()
        }
    return rawOfDer(der)
  }

  /** `r ‖ s`, 32 bytes each, as the two INTEGERs of a DER ECDSA signature. */
  fun derOfRaw(raw: ByteArray): ByteArray {
    if (raw.size != 64) throw Failure(BAD_WIRE)
    fun integer(bytes: ByteArray): ByteArray {
      val value = BigInteger(1, bytes).toByteArray() // minimal, with a leading zero when the top bit is set
      return byteArrayOf(0x02, value.size.toByte()) + value
    }
    val body = integer(raw.copyOf(32)) + integer(raw.copyOfRange(32, 64))
    return byteArrayOf(0x30, body.size.toByte()) + body
  }

  fun rawOfDer(der: ByteArray): ByteArray {
    fun fixed(value: ByteArray): ByteArray {
      val trimmed = value.dropWhile { it == 0.toByte() }.toByteArray()
      if (trimmed.size > 32) throw Failure(BAD_WIRE)
      return ByteArray(32 - trimmed.size) + trimmed
    }
    try {
      if (der[0] != 0x30.toByte() || der[1].toInt() != der.size - 2 || der[2] != 0x02.toByte()) throw Failure(BAD_WIRE)
      val rLength = der[3].toInt()
      val r = der.copyOfRange(4, 4 + rLength)
      if (der[4 + rLength] != 0x02.toByte()) throw Failure(BAD_WIRE)
      val sLength = der[5 + rLength].toInt()
      if (6 + rLength + sLength != der.size) throw Failure(BAD_WIRE)
      return fixed(r) + fixed(der.copyOfRange(6 + rLength, 6 + rLength + sLength))
    } catch (e: IndexOutOfBoundsException) {
      throw Failure(BAD_WIRE)
    }
  }

  // Hashing and encoding

  fun sha256(data: ByteArray): ByteArray = MessageDigest.getInstance("SHA-256").digest(data)

  fun sha256Hex(data: ByteArray): String = sha256(data).joinToString("") { "%02x".format(it) }

  fun hex(s: String): ByteArray = ByteArray(s.length / 2) { s.substring(it * 2, it * 2 + 2).toInt(16).toByte() }

  fun base64url(data: ByteArray): String = Base64.getUrlEncoder().withoutPadding().encodeToString(data)

  /** Null when the text is not base64url. Padding is accepted and not required. */
  fun fromBase64url(s: String): ByteArray? =
      try {
        Base64.getUrlDecoder().decode(s.trimEnd('='))
      } catch (e: IllegalArgumentException) {
        null
      }

  /** A string as JSON writes it, quotes included. Enough for the ids a grant carries. */
  fun jsonString(s: String): String =
      buildString {
        append('"')
        for (c in s) {
          when {
            c == '"' -> append("\\\"")
            c == '\\' -> append("\\\\")
            c < ' ' -> append("\\u%04x".format(c.code))
            else -> append(c)
          }
        }
        append('"')
      }

  // Recovery code (API contract, "Recovery blob")

  /** Crockford base32: no I, L, O or U, so a code read aloud or copied by hand has no look-alikes. */
  const val RECOVERY_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
  const val RECOVERY_CODE_LENGTH = 28

  /** 28 characters, 5 bits each (140 bits), from the system's random generator. */
  fun newRecoveryCode(): String = randomBytes(RECOVERY_CODE_LENGTH).map { RECOVERY_ALPHABET[it.toInt() and 0x1f] }.joinToString("")

  /**
   * What was typed, as the code itself: upper case, spaces and hyphens dropped, and the letters
   * the alphabet leaves out read as the digits they are mistaken for (O as 0, I and L as 1).
   * Null when it isn't 28 characters of the alphabet.
   */
  fun normalizeRecoveryCode(typed: String): String? {
    val mapped =
        typed.uppercase().mapNotNull { c ->
          when (c) {
            ' ', '-', '\n', '\t' -> null
            'O' -> '0'
            'I', 'L' -> '1'
            else -> c
          }
        }
    return if (mapped.size == RECOVERY_CODE_LENGTH && mapped.all { it in RECOVERY_ALPHABET }) mapped.joinToString("") else null
  }

  /** "K7Q2 M9X4 T6W1 …": groups of four, as it is shown and written down. */
  fun groupedRecoveryCode(code: String): String = code.chunked(4).joinToString(" ")

  /**
   * The key a recovery code locks the share with: Argon2id, 64 MiB, 3 passes, 1 lane, 32 bytes
   * (the contract's parameters; RFC 9106's second recommended memory and passes). It takes a few
   * seconds and 64 MiB of memory; callers run it off the main thread.
   */
  fun recoveryKey(code: String, salt: ByteArray): ByteArray {
    if (salt.size != 16) throw Failure(BAD_WIRE)
    val parameters =
        Argon2Parameters.Builder(Argon2Parameters.ARGON2_id)
            .withVersion(Argon2Parameters.ARGON2_VERSION_13)
            .withMemoryAsKB(64 * 1024)
            .withIterations(3)
            .withParallelism(1)
            .withSalt(salt)
            .build()
    return ByteArray(32).also { key ->
      Argon2BytesGenerator().run {
        init(parameters)
        generateBytes(utf8(code), key)
      }
    }
  }

  /** `0x01 ‖ salt(16) ‖ nonce(12) ‖ AES-256-GCM(share) ‖ tag(16)`, no associated data. */
  fun sealRecovery(share: ByteArray, code: String, salt: ByteArray, nonce: ByteArray): ByteArray {
    if (share.size != 32 || nonce.size != 12) throw Failure(BAD_WIRE)
    return byteArrayOf(0x01) + salt + seal(recoveryKey(code, salt), share, ByteArray(0), nonce)
  }

  /**
   * The share inside a recovery blob. Throws when the code is wrong (the tag doesn't verify) or
   * the blob isn't version 1 of the right length.
   */
  fun openRecovery(blob: ByteArray, code: String): ByteArray {
    if (blob.size != 1 + 16 + 12 + 32 + 16 || blob[0] != 0x01.toByte()) throw Failure(BAD_WIRE)
    return open(recoveryKey(code, blob.copyOfRange(1, 17)), blob.copyOfRange(17, blob.size), ByteArray(0))
  }

  /**
   * Six digits both phones show when a new phone asks for the key: each works them out from the new phone's own key (the one the share is wrapped to,
   * SPKI base64url) and the approval request's id. The first four bytes of the SHA-256, as a
   * number, modulo a million. What it covers and what it doesn't is said beside the Swift.
   */
  fun compareCode(key: String, requestId: String): String {
    val digest = sha256(utf8("leave:v1:device-compare:$requestId:$key"))
    val number = digest.take(4).fold(0L) { acc, b -> (acc shl 8) or (b.toLong() and 0xff) }
    return "%06d".format(number % 1_000_000)
  }
}
